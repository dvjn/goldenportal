import {
  AppWindow,
  BookOpen,
  Box,
  Boxes,
  Briefcase,
  Building,
  Cloud,
  Code,
  Component,
  Cpu,
  Database,
  FileText,
  GitBranch,
  Globe,
  KeyRound,
  Layers,
  type LucideIcon,
  type LucideProps,
  Network,
  Package,
  Rocket,
  Server,
  Shield,
  User,
  Users,
  Workflow,
} from "lucide-react";

// The icon names a blueprint can use, as internal/definition/blueprint.go lists them.
const icons: Record<string, LucideIcon> = {
  box: Box,
  boxes: Boxes,
  server: Server,
  database: Database,
  cloud: Cloud,
  globe: Globe,
  network: Network,
  cpu: Cpu,
  code: Code,
  "git-branch": GitBranch,
  package: Package,
  layers: Layers,
  component: Component,
  "app-window": AppWindow,
  workflow: Workflow,
  rocket: Rocket,
  users: Users,
  user: User,
  building: Building,
  briefcase: Briefcase,
  shield: Shield,
  "key-round": KeyRound,
  "book-open": BookOpen,
  "file-text": FileText,
};

export function BlueprintIcon({ icon, ...props }: { icon?: string } & LucideProps) {
  const Icon = icons[icon ?? ""] ?? Box;
  return <Icon {...props} />;
}
